// The headers of the C standard: all a Windows program (WinCC) gets from here;
// the others (dynasty.h, net.h...) are DynastyOS's own.
static const char *g_standard[] = {
    "stddef.h", "stdarg.h", "stdbool.h", "stdalign.h", "stdnoreturn.h", "iso646.h", "stdint.h",
    "inttypes.h", "wchar.h", "wctype.h", "uchar.h", "limits.h", "float.h", "errno.h", "assert.h",
    "stdio.h", "stdlib.h", "string.h", "strings.h", "ctype.h", "math.h", "time.h", "setjmp.h",
    "signal.h", "locale.h", 0,
};

const char *cc_builtin_header(const char *name)
{
    if (cc_target_win) {
        int std = 0;
        for (int i = 0; g_standard[i]; i++)
            if (cc_streq(g_standard[i], name))
                std = 1;
        if (!std)
            return 0;
    }
    for (const Header *h = g_headers; h->name; h++)
        if (cc_streq(h->name, name))
            return h->text;
    return 0;
}
