// tgmath.h: one name for the float and the double function -- sqrt(x) of a float
// calls sqrtf, of a double (or an integer) sqrt. Made with _Generic. (Only real
// numbers: the complex ones of complex.h are structures here.)
#pragma once
#include <math.h>

#define __wcc_tg1(fn, x) _Generic((x), float: fn##f, default: fn)(x)
#define __wcc_tg2(fn, x, y) _Generic((x) + (y), float: fn##f, default: fn)((x), (y))

#define sqrt(x) __wcc_tg1(sqrt, x)
#define cbrt(x) _Generic((x), float: cbrtf, default: cbrt)(x)
#define fabs(x) __wcc_tg1(fabs, x)
#define floor(x) __wcc_tg1(floor, x)
#define ceil(x) __wcc_tg1(ceil, x)
#define round(x) __wcc_tg1(round, x)
#define trunc(x) __wcc_tg1(trunc, x)
#define sin(x) __wcc_tg1(sin, x)
#define cos(x) __wcc_tg1(cos, x)
#define tan(x) __wcc_tg1(tan, x)
#define asin(x) __wcc_tg1(asin, x)
#define acos(x) __wcc_tg1(acos, x)
#define atan(x) __wcc_tg1(atan, x)
#define sinh(x) __wcc_tg1(sinh, x)
#define cosh(x) __wcc_tg1(cosh, x)
#define tanh(x) __wcc_tg1(tanh, x)
#define exp(x) __wcc_tg1(exp, x)
#define exp2(x) __wcc_tg1(exp2, x)
#define log(x) __wcc_tg1(log, x)
#define log2(x) __wcc_tg1(log2, x)
#define log10(x) __wcc_tg1(log10, x)
#define atan2(y, x) __wcc_tg2(atan2, y, x)
#define pow(x, y) __wcc_tg2(pow, x, y)
#define fmod(x, y) __wcc_tg2(fmod, x, y)
#define hypot(x, y) __wcc_tg2(hypot, x, y)
#define fmin(x, y) __wcc_tg2(fmin, x, y)
#define fmax(x, y) __wcc_tg2(fmax, x, y)
#define copysign(x, y) __wcc_tg2(copysign, x, y)
// these have no float form here: the double one for all
#define asinh(x) asinh(x)
#define acosh(x) acosh(x)
#define atanh(x) atanh(x)
#define expm1(x) expm1(x)
#define log1p(x) log1p(x)
#define erf(x) erf(x)
#define erfc(x) erfc(x)
#define tgamma(x) tgamma(x)
#define lgamma(x) lgamma(x)
